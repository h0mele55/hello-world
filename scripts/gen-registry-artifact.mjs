#!/usr/bin/env node
/**
 * Writes src/lib/chain/registry-artifact.ts from the Foundry build output, so
 * the TypeScript side uses exactly the ABI and bytecode the tests ran against.
 * CI rebuilds the contract, re-runs this and fails on any diff.
 *
 *   (cd contracts && forge build) && node scripts/gen-registry-artifact.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { keccak256 } from 'viem';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BUILD = path.join(ROOT, 'contracts/out/AuditReportRegistry.sol/AuditReportRegistry.json');
const TARGET = path.join(ROOT, 'src/lib/chain/registry-artifact.ts');

if (!fs.existsSync(BUILD)) {
  console.error(`No build output at ${path.relative(ROOT, BUILD)}. Run: (cd contracts && forge build)`);
  process.exit(1);
}

const artifact = JSON.parse(fs.readFileSync(BUILD, 'utf8'));
const bytecode = artifact.bytecode.object;
const deployedBytecode = artifact.deployedBytecode.object;
if (!/^0x[0-9a-f]+$/.test(bytecode) || !/^0x[0-9a-f]+$/.test(deployedBytecode)) {
  console.error('Build output has no plain bytecode (unlinked libraries or immutables?). Refusing.');
  process.exit(1);
}

const source = `// Generated by scripts/gen-registry-artifact.mjs from contracts/out. Do not edit.
// Regenerate after any change to contracts/src: (cd contracts && forge build) && node scripts/gen-registry-artifact.mjs

export const registryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;

export const registryBytecode = '${bytecode}' as const;

/** keccak256 of the runtime bytecode: what eth_getCode returns for a genuine deployment. */
export const registryRuntimeBytecodeHash = '${keccak256(deployedBytecode)}' as const;
`;

fs.writeFileSync(TARGET, source);
console.log(`Wrote ${path.relative(ROOT, TARGET)}`);
